@pytest.mark.asyncio
async def test_create_github_issue_write_ignores_arbitrary_personal_github_secret():
    # A read may fall back to any available github-ish secret, but a public write
    # must NOT auto-author under an arbitrary teammate PAT. Only the canonical
    # GITHUB_TOKEN/GH_TOKEN default (or an explicit key / project binding) is a
    # valid write identity, so with only GITHUB_TOKEN_ALICE present the write has
    # no candidate and degrades to no_write_token.
    async def fake_get_secret(key_name, *args, **kwargs):
        return {"GITHUB_TOKEN_ALICE": "alice-pat"}.get(key_name)

    async def fake_list_secrets(*args, **kwargs):
        return [{"key_name": "GITHUB_TOKEN_ALICE", "category": "github", "agent_access_level": "available"}]

    with bind_agent_context({"user_id": "u", "org_id": "o"}), patch(
        f"{_H}.async_resolve_project_bound_env_tokens", new=AsyncMock(return_value={})
    ), patch(
        f"{_H}.async_list_secrets", new=AsyncMock(side_effect=fake_list_secrets)
    ), patch(
        f"{_H}.async_get_secret", new=AsyncMock(side_effect=fake_get_secret)
    ), patch(f"{_H}.async_create_repo_issue", new=AsyncMock()) as create:
        result = await _handle_create_github_issue(repo="uwear-ai/uwear-backend", title="X")

    payload = json.loads(result)
    assert payload["no_write_token"] is True
    create.assert_not_awaited()


@pytest.mark.asyncio
async def test_connector_posts_issue_with_only_set_fields():
    fake_created = {"number": 7, "html_url": "https://github.com/uwear-ai/uwear-backend/issues/7", "title": "X"}
    with patch(
        "brain.systems.cortex.project_context.github._async_request",
        new=AsyncMock(return_value=fake_created),
    ) as request:
        payload = await async_create_repo_issue(
            "uwear-ai/uwear-backend",
            title="X",
            body="",  # empty body must be omitted
            labels=["bug", "  "],
            assignees=[],
            token="write-token",
        )

    assert payload["repo"] == "uwear-ai/uwear-backend"
    assert payload["issue"]["number"] == 7
    request.assert_awaited_once()
    assert request.await_args.args[1] == "POST"
    assert request.await_args.args[2] == "/repos/uwear-ai/uwear-backend/issues"
    assert request.await_args.kwargs["token"] == "write-token"
    body = request.await_args.kwargs["json"]
    assert body == {"title": "X", "labels": ["bug"]}  # empty body/assignees dropped


