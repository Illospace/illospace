async def test_read_assign_comment_and_claim(rpc, rpc_token, github_client):
    _, token = rpc_token
    result = await call(rpc, token, "github_create_issue", CREATE)
    number = result["result"]["issue"]["number"]
    for name, args in [
        ("github_search_issues", {"query": "Stable"}),
        ("github_get_issue", {"repo": REPO, "number": number}),
        ("github_assign_issue", {"repo": REPO, "number": number, "assignee": "ada"}),
        ("github_comment_issue", {"repo": REPO, "number": number, "body": "A team comment."}),
    ]:
        assert (await call(rpc, token, name, args))["decision"] == (
            "draft" if name in {"github_assign_issue", "github_comment_issue"} else "allow"
        )
    assert (await call(rpc, token, "claims_take", {"key": "alert:1", "note": "Handle the alert"}))[
        "result"
    ] is True
    assert (await call(rpc, token, "claims_take", {"key": "alert:1"}))["result"] is False


async def test_claim_concurrency(app, rpc_token):
    run, _ = rpc_token

    async def take():
        async with app.state.ctx.pool.connection() as conn:
            return await claims.take(conn, "alert:race", run["id"])

    assert sum(await asyncio.gather(*(take() for _ in range(12)))) == 1


async def test_work_one_message_then_edit(app, rpc, rpc_token, github_client, slack_client):
    _, token = rpc_token
    ctx = app.state.ctx
    ctx.workspace.config.github.work_channel = "C_ACME_TEAM"
    result = await call(rpc, token, "work_start", {**CREATE, "assignee": "ada"})
    assert result["decision"] == "draft"
    async with ctx.pool.connection() as conn:
        await conn.execute("UPDATE drafts SET state='approved'")
        draft = await one(conn, "SELECT * FROM drafts")
    result = {"result": await perform_draft(ctx, draft)}
    assert result["result"]["lane_id"]
    assert len([c for c in slack_client.calls if c["method"] == "chat_postMessage"]) == 1
    await refresh_statuses(ctx)
    assert not [c for c in slack_client.calls if c["method"] == "chat_update"]
    github_client.issues[0]["labels"] = ["agent:working"]
    await poll(ctx)
    await refresh_statuses(ctx)
    assert len([c for c in slack_client.calls if c["method"] == "chat_update"]) == 1
    async with ctx.pool.connection() as conn:
        lane = await one(conn, "SELECT * FROM lanes")
        assert lane["slack_channel"] == "C_ACME_TEAM" and lane["slack_ts"]
        assert (
            lane["owner_person_id"]
            == (await one(conn, "SELECT id FROM people WHERE key='ada'"))["id"]
        )
    assert [c for c in slack_client.calls if c["method"] == "chat_update"][0]["text"].startswith(
        "Working · Stable failure"
    )


async def test_work_keeps_the_ticket_when_github_refuses_the_assignment(
    app, rpc, rpc_token, github_client, slack_client
):
    _, token = rpc_token
    ctx = app.state.ctx
    ctx.workspace.config.github.work_channel = "C_ACME_TEAM"
    github_client.refuse_assignment = True
    assert (await call(rpc, token, "work_start", {**CREATE, "assignee": "ada"}))[
        "decision"
    ] == "draft"
    async with ctx.pool.connection() as conn:
        await conn.execute("UPDATE drafts SET state='approved'")
        draft = await one(conn, "SELECT * FROM drafts")
    result = await perform_draft(ctx, draft)
    assert result["created"] and result["lane_id"] and result["assigned"] is False
    posts = [c for c in slack_client.calls if c["method"] == "chat_postMessage"]
    assert len(posts) == 1
    assert posts[0]["text"].startswith("Open · Stable failure · https://github.com/")
    assert posts[0]["text"].endswith("GitHub refused the assignment. The ticket has no owner.")
    # The note stays after a refresh, because the lane holds it as an event.
    await refresh_statuses(ctx)
    assert not [c for c in slack_client.calls if c["method"] == "chat_update"]
    async with ctx.pool.connection() as conn:
        lane = await one(conn, "SELECT * FROM lanes")
        assert lane["owner_person_id"] is None


