async def test_public_draft_performer_checks_approval(app, rpc, rpc_token, github_client):
    _, token = rpc_token
    ctx = app.state.ctx
    github_client.repositories[REPO] = {"private": False}
    assert (await call(rpc, token, "github_create_issue", CREATE))["decision"] == "draft"
    async with ctx.pool.connection() as conn:
        draft = await one(conn, "SELECT * FROM drafts")
    with pytest.raises(ValueError):
        await perform_draft(ctx, draft)
    async with ctx.pool.connection() as conn:
        await conn.execute("UPDATE drafts SET state='approved' WHERE id=%s", (draft["id"],))
        draft = await one(conn, "SELECT * FROM drafts")
    assert (await perform_draft(ctx, draft))["created"]
    async with ctx.pool.connection() as conn:
        audit = await all_rows(conn, "SELECT * FROM audit")
        assert audit[0]["decision"] == "draft"


