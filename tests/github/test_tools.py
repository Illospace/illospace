"""Tools enforce repository and assignee limits before GitHub writes."""

import asyncio

import pytest

from illo.db import all_rows, one
from illo.ledger import claims
from illo.sources.github import perform_draft, poll
from illo.tools.work import refresh_statuses
from tests.tool_results import read_result

REPO = "acme-example/engine"
CREATE = {
    "repo": REPO,
    "title": "Stable failure",
    "body": "The worker fails.",
    "signature": "Stable failure",
}


async def call(rpc, token, name, args):
    return read_result((await rpc(token, "tools/call", {"name": name, "arguments": args})).json()["result"])


async def test_duplicate_checks_open_and_closed_and_force(rpc, rpc_token, github_client):
    _, token = rpc_token
    github_client.issues = [{"number": 5, "title": "Stable failure", "state": "closed"}]
    first = await call(rpc, token, "github_create_issue", CREATE)
    assert first["result"]["created"]
    body = first["result"]["issue"]["body"]
    assert body.startswith("> *This was generated by AI during triage.*")
    assert "<!-- illo:run:" in body
    second = await call(rpc, token, "github_create_issue", CREATE)
    assert not second["result"]["created"]
    assert len(second["result"]["matches"]) == 2
    forced = await call(
        rpc,
        token,
        "github_create_issue",
        {**CREATE, "force_new_reason": "A separate occurrence needs its own fix."},
    )
    assert forced["result"]["created"]
    searches = [c for c in github_client.calls if c["method"] == "search_issues"]
    assert all(c["state"] == "all" for c in searches)


